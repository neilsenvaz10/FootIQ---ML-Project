"""Phase 4.33 approved cleanup. Usage: execute_cleanup.py manifest | delete.
manifest: builds approved_manifest.csv (path, bytes, sha256, group, reason) from the approved groups only and prints the reconciled totals (actual file sizes).
delete:   removes exactly the files of approved_manifest.csv (each only if it still has the recorded size; read-only attributes are cleared first), writes deletion_log.csv, then removes
          directories that became empty INSIDE the deleted trees (never data/supervised/pytest_tmp itself, never a directory holding other files).
Approved groups: S1 bytecode caches, S2 pytest_tmp contents, S3 frontend/dist, A1 p424 backup, A2 pre-sync snapshot, A4 p417 duplicates with a verified twin, A12 dataset zip, A14 logs (minus cited evidence)."""
import csv
import hashlib
import json
import os
import stat
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
MAN = HERE / "approved_manifest.csv"
LOG = HERE / "deletion_log.csv"
mode = sys.argv[1]
inv = {r["path"]: int(r["bytes"]) for r in csv.DictReader(open(HERE / "inventory.csv", encoding="utf-8"))}
KEEP_A14 = {"logs/supervisor.log", "data/supervised/full_backend_run_2.txt", "data/supervised/live_test_backend.log", "data/supervised/investigation_output.txt", "data/supervised/investigation_analysis.txt", "data/supervised/rehearsal_run_output.txt"}


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for c in iter(lambda: fh.read(1 << 22), b""):
            h.update(c)
    return h.hexdigest()


def groups():
    cond = json.loads((HERE / "conditions.json").read_text(encoding="utf-8"))
    out = []
    safe = list(csv.DictReader(open(HERE / "safe_delete_manifest.csv", encoding="utf-8")))
    for r in safe:
        out.append((r["path"], r["group"], {"S1": "bytecode cache, regenerated on import", "S2": "pytest scratch, recreated by conftest", "S3": "frontend build output, regenerated by npm run build"}[r["group"]]))
    for p in inv:
        if p.startswith("data/backups/p424_pre_reconcile_20261028/"):
            out.append((p, "A1", "Phase 4.24 backup; p428 and p430 backups verified (hash and integrity)"))
        if p.startswith("data/supervised/footiq.before-sync.sqlite"):
            out.append((p, "A2", "pre-sync snapshot; rebuilt from the baseline inputs it is identical except build timestamps; every record exists in production"))
    for p, size, h, twin in cond["A4_delete"]:
        out.append((p, "A4", f"byte-identical twin (sha256 {h[:12]}...): {twin}"))
    out.append(("FootIQ_Dataset_Submission.zip", "A12", "all 34 members identical in the unpacked FootIQ_Dataset_Submission folder"))
    for p in cond["A14"]:
        if p not in KEEP_A14:
            out.append((p, "A14", "routine access log or test progress output; no error, not cited as evidence"))
    return out


if mode == "manifest":
    rows, seen = [], set()
    for p, g, why in groups():
        if p in seen:
            continue
        seen.add(p)
        f = ROOT / p
        if not f.is_file():
            print("MISSING", p)
            continue
        rows.append((p, f.stat().st_size, sha(f), g, why))
    with open(MAN, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["path", "bytes", "sha256", "group", "reason"])
        w.writerows(rows)
    tot = {}
    for r in rows:
        tot.setdefault(r[3], [0, 0])
        tot[r[3]][0] += 1
        tot[r[3]][1] += r[1]
    for g, (n, b) in sorted(tot.items()):
        print(f"{g:4s} {n:5d} files {b / 1e6:9.1f} MB")
    print(f"TOTAL {len(rows)} files {sum(r[1] for r in rows) / 1e6:.1f} MB ({sum(r[1] for r in rows)} bytes)")
elif mode == "delete":
    rows = list(csv.DictReader(open(MAN, encoding="utf-8")))
    n = b = skipped = 0
    dirs = set()
    with open(LOG, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["timestamp_utc", "group", "path", "bytes", "status"])
        for r in rows:
            f = ROOT / r["path"]
            ts = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            if not f.is_file() or f.stat().st_size != int(r["bytes"]):
                skipped += 1
                w.writerow([ts, r["group"], r["path"], r["bytes"], "SKIPPED missing or size changed"])
                continue
            try:
                try:
                    os.remove(f)
                except PermissionError:
                    os.chmod(f, stat.S_IWRITE)
                    os.remove(f)
            except OSError as e:
                skipped += 1
                w.writerow([ts, r["group"], r["path"], r["bytes"], f"SKIPPED {type(e).__name__}"])
                continue
            w.writerow([ts, r["group"], r["path"], r["bytes"], "deleted"])
            n += 1
            b += int(r["bytes"])
            dirs.add(f.parent)
        removed = 0
        protect = {(ROOT / "data" / "supervised" / "pytest_tmp").resolve(), ROOT.resolve(), (ROOT / "data").resolve(), (ROOT / "data" / "supervised").resolve(), (ROOT / "data" / "backups").resolve(), (ROOT / "logs").resolve()}
        for d in sorted(dirs, key=lambda x: len(str(x)), reverse=True):
            cur = d
            while cur.resolve() not in protect and ROOT.resolve() in cur.resolve().parents:
                try:
                    os.rmdir(cur)                                           # only succeeds when the directory is empty
                    removed += 1
                except OSError:
                    break
                cur = cur.parent
    print(f"deleted {n} of {len(rows)} files, {b} bytes ({b / 1e6:.1f} MB); skipped {skipped}; empty directories removed {removed}")
