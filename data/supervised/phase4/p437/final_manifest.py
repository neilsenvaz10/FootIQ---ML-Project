"""Phase 4.37: FINAL Git inclusion / exclusion manifests (read-only; nothing is staged). Applies the restricted-removal plan and the sanitized replacements on top of the Phase 4.34 rules (out/proposed_manifest.csv, regenerated by manifest.py).
Writes out/final_inclusion_manifest.csv (path, publish_path, bytes, decision), out/final_exclusion_manifest.csv, out/final_totals.json and re-scans the final set for restricted data files."""
import csv, json, re, zlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[4]
OUT = Path(__file__).resolve().parent / "out"
MIB = 1024 * 1024
base = list(csv.DictReader(open(OUT / "proposed_manifest.csv", encoding="utf-8")))
plan = {r["path"]: r for r in csv.DictReader(open(OUT / "restricted_removal_plan.csv", encoding="utf-8"))}
REPLACED = {"data/miniproject/matches.csv", "data/miniproject/data_audit.csv", "data/miniproject/season_coverage.csv"}
inc, exc = [], []
for r in base:
    p, b = r["path"], int(r["bytes"])
    if r["decision"] == "EXCLUDE":
        exc.append((p, b, r["rule"]))
        continue
    if p in REPLACED:
        exc.append((p, b, "original replaced by the sanitized copy (130 World Cup 2026 rows from an API-Football provider file and news / FIFA pages removed)"))
        continue
    if p.startswith("data/release_candidates/miniproject/"):
        inc.append((p, "data/miniproject/" + p.rsplit("/", 1)[1], b, r["decision"], "sanitized replacement, published at the original path"))
        continue
    pl = plan.get(p)
    if pl and pl["category"] in "ABCDE" and pl["action"] in ("git rm --cached", "do not add"):
        exc.append((p, b, f"restricted category {pl['category']}: {pl['reason']}"))
        continue
    if p == "docs/mini-project/phase4/P4_13B_DATE_VERIFICATION_SHEET.csv":
        exc.append((p, b, "carries football-data.org dates: sanitized copy in data/evidence/sanitized/"))
        continue
    inc.append((p, p, b, r["decision"], r["rule"]))
with open(OUT / "final_inclusion_manifest.csv", "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh); w.writerow(["path", "publish_path", "bytes", "decision", "rule"]); w.writerows(inc)
with open(OUT / "final_exclusion_manifest.csv", "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh); w.writerow(["path", "bytes", "reason"]); w.writerows(exc)
est = 0
for p, pp, b, d, why in inc:
    if d != "GIT":
        continue
    if p.lower().endswith((".png", ".jpg", ".pdf", ".zip", ".woff2", ".gz")):
        est += b
        continue
    c = zlib.compressobj(6); n = 0
    with open(ROOT / p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 22), b""):
            n += len(c.compress(chunk))
    est += n + len(c.flush())
git = [x for x in inc if x[3] == "GIT"]; lfs = [x for x in inc if x[3] == "LFS"]
tot = dict(git_files=len(git), git_bytes=sum(x[2] for x in git), git_compressed_estimate_bytes=est, lfs_files=len(lfs), lfs_bytes=sum(x[2] for x in lfs), excluded_files=len(exc), excluded_bytes=sum(x[1] for x in exc),
           lfs=[(x[0], x[2]) for x in sorted(lfs, key=lambda x: -x[2])], largest_git=[(x[0], x[2]) for x in sorted(git, key=lambda x: -x[2])[:6]])
# re-scan the final set for restricted DATA files (code / docs that merely name a source are fine)
RX = {"api-football": rb"api-?football|apifootball|api_football|api-sports|apisports|provider_fixture_id|provider_score", "statsbomb-data": rb"statsbomb_|\"statsbomb\"|open-data/", "footballdata-uk": rb"footballdatauk_|football-data\.co\.uk/mmz", "fixturedownload": rb"fixturedownload_(score|date|local|utc)", "footballdata-org": rb"provider_date|api\.football-data\.org|X-Auth-Token"}
rx = {k: re.compile(v, re.I) for k, v in RX.items()}
CODE = (".py", ".md", ".txt", ".js", ".jsx", ".ps1", ".sha256", ".example", ".pdf", ".yml", ".yaml", ".toml", ".gitignore", ".gitattributes", ".html", ".css")
res = []
for p, pp, b, d, why in inc:
    if p.lower().endswith(CODE) or d == "LFS" and p.endswith(".pkl"):
        continue
    hits = {}
    with open(ROOT / p, "rb") as fh:
        data = fh.read(40 * MIB)
    for k, r_ in rx.items():
        n = len(r_.findall(data))
        if n:
            hits[k] = n
    if hits:
        res.append((p, hits))
tot["residual_data_files_with_markers"] = res
json.dump(tot, open(OUT / "final_totals.json", "w"), indent=1)
print({k: v for k, v in tot.items() if k not in ("lfs", "largest_git", "residual_data_files_with_markers")})
print("LFS:", [(a, round(b / MIB, 1)) for a, b in tot["lfs"]])
print("residual data files with markers:", len(res))
for p, h in res[:40]: print("  ", p[:100], h)
