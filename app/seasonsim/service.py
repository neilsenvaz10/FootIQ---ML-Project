class SimError(ValueError):
    """User-facing problem (wrong action, out-of-range input, blocked league)."""


def _season_rows(conn, key: str, season: str) -> list[dict]:
    return [dict(r) for r in conn.execute(
        "SELECT m.record_id, m.match_date, m.status, COALESCE(m.model_home_entity, m.home_entity_id) h, COALESCE(m.model_away_entity, m.away_entity_id) a, m.home_entity_id he, m.away_entity_id ae, "
        "COALESCE(m.home_goals_90, m.home_goals_final) hg, COALESCE(m.away_goals_90, m.away_goals_final) ag, m.competition_id, m.source_system, m.home_name, m.away_name "
        "FROM matches m WHERE m.competition_key=? AND m.season=? AND m.kind='club' ORDER BY m.match_date, m.record_id", (key, season))]


def _names(conn, ids) -> dict:
    q = ",".join("?" * len(ids))
    return {r[0]: r[1] for r in conn.execute(f"SELECT entity_id, display_name FROM teams WHERE entity_id IN ({q})", list(ids))}


def live_probabilities(conn, key: str, season: str, remaining: list[dict]) -> pd.DataFrame:
    """Frozen-model probabilities and expected goals for the remaining fixtures from the state at the data cut-off (every fixture is featurised from that state at its own date, or the day after the cut-off)."""
    import predict

    lg, V, tiers = predict._club_runtime()
    latest = V.dt.max()
    comp_id = C.BY_KEY[key]["source_id"]
    tier = tiers.get(comp_id, np.nan)
    F2s, F1s = [], []
    for r in remaining:
        dt = max(pd.Timestamp(r["match_date"]), latest + pd.Timedelta(days=1))
        F2, F1 = predict.club_features_fast(r["h"], r["a"], comp_id, season, dt, tier)
        F2s.append(F2)
        F1s.append(F1)
    F2, F1 = pd.concat(F2s, ignore_index=True), pd.concat(F1s, ignore_index=True)
    scored = predict.club_score(F2, F1)
    p1 = np.array([s["p1"] for s in scored])
    p2 = np.array([s["p2"] for s in scored])
    return pd.DataFrame(dict(record_id=[r["record_id"] for r in remaining], p1_H=p1[:, 0], p1_D=p1[:, 1], p1_A=p1[:, 2], p2_H=p2[:, 0], p2_D=p2[:, 1], p2_A=p2[:, 2],
                             lam_h=F2.lambda_home.values, lam_a=F2.lambda_away.values, n_h=[s["n_h"] for s in scored], n_a=[s["n_a"] for s in scored])), pd.Timestamp(latest)


def _league_lams(conn, key: str) -> tuple:
    r = conn.execute("SELECT AVG(COALESCE(home_goals_90, home_goals_final)), AVG(COALESCE(away_goals_90, away_goals_final)) FROM matches WHERE competition_key=? AND kind='club' AND status='completed' AND match_date>='2018-08-01'", (key,)).fetchone()
    return (float(r[0] or 1.5), float(r[1] or 1.2))


def build_input(conn, key: str, season: str, probs: pd.DataFrame, rows: list[dict], method: str, prob_col: str = "p1") -> tuple:
    teams = sorted({r["h"] for r in rows} | {r["a"] for r in rows})
    idx = {t: i for i, t in enumerate(teams)}
    names = _names(conn, teams)
    played = [r for r in rows if r["status"] in eligibility.COMPLETED and r["hg"] is not None]
    pid = {r["record_id"] for r in played}
    rem = [r for r in rows if r["record_id"] not in pid]
    pr = probs.set_index("record_id").loc[[r["record_id"] for r in rem]]
    if method == "S3":
        raise SimError("scoreline method S3 is not wired into the service (it is only used by the benchmark until it is selected)")
    pmf, info = scoreline.build_pmf(method, pr[[f"{prob_col}_H", f"{prob_col}_D", f"{prob_col}_A"]].values, pr.lam_h.values, pr.lam_a.values, key, _league_lams(conn, key))
    inp = SeasonInput(teams=teams, names=[names.get(t, t) for t in teams], played_home=np.array([idx[r["h"]] for r in played], dtype=int), played_away=np.array([idx[r["a"]] for r in played], dtype=int),
                      played_hg=np.array([int(r["hg"]) for r in played], dtype=int), played_ag=np.array([int(r["ag"]) for r in played], dtype=int),
                      fix_home=np.array([idx[r["h"]] for r in rem], dtype=int), fix_away=np.array([idx[r["a"]] for r in rem], dtype=int), pmf=pmf, fix_ids=[r["record_id"] for r in rem])
    return inp, info, rem


def status(key: str, season: str, today: Optional[date] = None, db_path=None) -> dict:
    conn = store_db.connect(db_path, readonly=True)
    try:
        st = eligibility.assess(conn, key, season, today)
        cfg = settings.load()
        st["limits"] = dict(default=cfg["default_simulations"], min=cfg["min_simulations"], max=cfg["max_simulations"])
        st["limitations"] = LIMITATIONS
        st["points_only"]["limitations"] = POINTS_LIMITATIONS
        st["saved_runs"] = conn.execute("SELECT COUNT(*) FROM simulation_runs WHERE competition_key=? AND season=?", (key, season)).fetchone()[0]
        return st
    finally:
        conn.close()


def _freshness(conn, key: str, season: str, rows: list[dict]) -> dict:
    last_sync = conn.execute("SELECT MAX(finished_utc) FROM sync_runs WHERE competition_key=? AND outcome='ok' AND kind<>'baseline_import'", (key,)).fetchone()[0]
    src = {}
    for r in rows:
        if r["status"] in eligibility.COMPLETED:
            src[(r["source_system"] or "unknown").split(" (")[0]] = src.get((r["source_system"] or "unknown").split(" (")[0], 0) + 1
    return dict(last_sync_utc=last_sync, completed_results_by_source=src)


def run_simulation(key: str, season: str, n: Optional[int], seed: Optional[int], user_action: str, include_experimental: bool = False, now: Optional[datetime] = None,
                   today: Optional[date] = None, db_path=None) -> dict:
    if user_action != EXPLICIT_ACTION:
        raise SimError("a season simulation runs only when the user explicitly presses Run season simulation")
    cfg = settings.load()
    n = int(n or cfg["default_simulations"])
    if not cfg["min_simulations"] <= n <= cfg["max_simulations"]:
        raise SimError(f"the number of simulations must be between {cfg['min_simulations']} and {cfg['max_simulations']}")
    now = now or datetime.now(timezone.utc)
    seed = int(seed) if seed is not None else secrets.randbits(31)
    conn = store_db.connect(db_path)
    try:
        st = eligibility.assess(conn, key, season, today)
        if not st["can_simulate"]:
            raise SimError("simulation blocked: " + "; ".join(st["blockers"]))
        profile = rules.get_profile(key, season)
        method = cfg["scoreline_method"]
        rows = _season_rows(conn, key, season)
        rem = [r for r in rows if not (r["status"] in eligibility.COMPLETED and r["hg"] is not None)]
        probs, latest_model = live_probabilities(conn, key, season, rem)
        inp, info, rem = build_input(conn, key, season, probs, rows, method)
        result = engine.simulate(inp, profile, n, seed)
        summary = engine.summarize(result, inp, profile)
        experimental = None
        if include_experimental:
            inp2, _, _ = build_input(conn, key, season, probs, rows, method, prob_col="p2")
            s2 = engine.summarize(engine.simulate(inp2, profile, n, seed), inp2, profile)
            experimental = dict(label="Experimental comparison: club v2-r1 (development-validated only, not a validated model)", teams=[{k: t[k] for k in ("name", "expected_points", "p_title", "p_top4", "p_relegation")} for t in s2["teams"]])
        import forecast

        ids, hashes = forecast.model_ids(), forecast.artifact_hashes()
        input_hash = hashlib.sha256(json.dumps([[r["record_id"], r["status"], r["hg"], r["ag"]] for r in rows] + probs[["p1_H", "p1_D", "p1_A", "lam_h", "lam_a"]].round(10).values.tolist(), default=str).encode()).hexdigest()
        latest_comp = st["latest_result"]
        assumptions = dict(
            created_utc=now.strftime("%Y-%m-%dT%H:%M:%SZ"), note=NOTE, user_action=user_action, simulations=n, seed=seed, models=dict(primary=ids["club_v1"], experimental_comparison=ids["club_v2_r1"]), artifact_sha256=hashes,
            probability_state="frozen club v1 features at the data cut-off, static during the simulation", data_cutoff=dict(latest_result_in_competition=latest_comp, latest_result_in_model_history=str(latest_model.date())),
            freshness=_freshness(conn, key, season, rows), eligibility=dict(state=st["state"], reasons=st["reasons"], notes=st["notes"], counts=st["counts"], thresholds=st["thresholds"]),
            scoreline=dict(info, validation=cfg["scoreline_validation"]), rule_profile=dict(profile_id=f"{key}|{season}", status=profile["status"], bands=profile["bands"], criteria=profile["criteria"], sources=profile["sources"], interpretation_notes=profile.get("interpretation_notes", [])),
            remaining_fixtures=len(rem), input_sha256=input_hash, limitations=LIMITATIONS, standard_error_max=summary["standard_error_max"])
        result_json = dict(summary=summary, experimental=experimental, positions=dict(bands=profile["bands"]))
        with conn:
            run_id = conn.execute("INSERT INTO simulation_runs(created_utc, competition_key, season, n_simulations, seed, model_id, data_cutoff_date, assumptions_json, result_json) VALUES (?,?,?,?,?,?,?,?,?)",
                                  (assumptions["created_utc"], key, season, n, seed, ids["club_v1"], latest_comp, json.dumps(assumptions), json.dumps(result_json))).lastrowid
        return dict(run_id=run_id, competition_key=key, season=season, assumptions=assumptions, result=result_json)
    finally:
        conn.close()


def list_runs(key: str, season: str, db_path=None) -> list[dict]:
    conn = store_db.connect(db_path, readonly=True)
    try:
        out = []
        for r in conn.execute("SELECT simulation_run_id AS run_id, created_utc, n_simulations, seed, model_id, data_cutoff_date, assumptions_json FROM simulation_runs WHERE competition_key=? AND season=? ORDER BY simulation_run_id DESC", (key, season)):
            d = dict(r)
            d["mode"] = json.loads(d.pop("assumptions_json")).get("mode", "final_positions")
            out.append(d)
        return out
    finally:
        conn.close()


def get_run(run_id: int, db_path=None) -> dict:
    conn = store_db.connect(db_path, readonly=True)
    try:
        r = conn.execute("SELECT * FROM simulation_runs WHERE simulation_run_id=?", (run_id,)).fetchone()
        if not r:
            raise SimError(f"no saved simulation run {run_id}")
        return dict(run_id=r["simulation_run_id"], competition_key=r["competition_key"], season=r["season"], assumptions=json.loads(r["assumptions_json"]), result=json.loads(r["result_json"]))
    finally:
        conn.close()


POINTS_LIMITATIONS = LIMITATIONS[:1] + [
    "Only win, draw and loss are simulated (3 / 1 / 0 points). No score is generated and no tie is settled by chance, so there is no predicted table and no exact title, top-four or relegation probability.",
    "Where title, top-four and relegation are shown they are lower and upper bounds, not exact probabilities: clubs level on points are separated by goals or by deciders that are not simulated, and such cases stay unresolved and widen the range.",
    "The clubs are listed by expected final points only. Equal or close points do not imply a league position.",
    "Fixtures whose date has passed but have no verified result are simulated like future fixtures.",
    "Backtest evidence (2024-25 and 2025-26, three cut-offs per season): the 10-90% intervals contained the real final points about 75% of the time instead of 80%, so they (and the ranges built on the same simulations) are somewhat too narrow.",
    "These are estimates from a modest model, not predictions of what will happen, and not betting advice.",
]

BOUNDS_LABEL = "Experimental \u2014 position ranges (lower and upper bounds, not exact probabilities)"
BOUNDS_BANDS = (("title", "Title"), ("top4", "Top four"), ("relegation", "Relegation"))
BOUNDS_MEANING = dict(
    guaranteed="Lower bound: the share of simulated seasons in which the club is in this group whatever the scores of the unplayed matches turn out to be.",
    possible="Upper bound: the share of simulated seasons in which the club could be in this group for some scores of the unplayed matches.",
    unresolved="Possible minus guaranteed: the share of simulated seasons that the points and the verified rules cannot settle (the order depends on goals that are not simulated, or on a decider that is never simulated).")
BOUNDS_METHOD = ("In every simulated season (win, draw or loss only) the best and the worst finishing position that each club could still have under the league's verified tie-break rules are computed from the points, "
                 "the real results already played, and what a win, draw or loss implies for goal difference and goals scored. No score is invented and no tie is settled by chance. "
                 "Guaranteed counts the seasons in which even the worst case is inside the group; possible counts the seasons in which the best case is.")
BOUNDS_LIMITATIONS = [
    "These are lower and upper bounds, not exact probabilities: under the model the true chance lies somewhere between them. A wide range means that goal difference (or a decider that is never simulated) would decide the matter.",
    "The ranges describe tie-break uncertainty only. They inherit every limitation of the simulation behind them: the frozen model's win / draw / loss chances are static during the season, and in backtests the 10-90% points intervals were about 75% reliable instead of 80%, so the ranges are probably a little too narrow.",
    "Sampling error of the simulation is given for every value (a few tenths of a percentage point at 10,000 simulations).",
    "Points deductions or other sanctions that are not in our data are not included.",
]


def _bounds_unavailable(reason: str) -> dict:
    return dict(status="unavailable", label=BOUNDS_LABEL, reason=reason)


def build_position_bounds(key: str, season: str, teams: list, names: list, idx: dict, played: list, fh: np.ndarray, fa: np.ndarray, pr: np.ndarray, n: int, seed: int, points: np.ndarray) -> dict:
    """Lower and upper bounds (guaranteed / possible / unresolved) of the title, top-four and relegation probabilities, from the SAME win / draw / loss draws as the points simulation.
    Never raises for a rules or scope reason: it returns status "unavailable" with the reason instead, and the points-only result is unaffected."""
    cfg = settings.load().get("points_only", {}).get("position_bounds", {})
    if not cfg.get("enabled"):
        return _bounds_unavailable("position ranges are switched off in config/season_sim.json")
    if key not in cfg.get("scope", []):
        return _bounds_unavailable("position ranges are available for the Bundesliga and La Liga only: they need verified tie-break settings for the league, which the other leagues do not have yet")
    try:
        profile = rules.get_profile(key, season)
    except rules.RuleBlocked as exc:
        return _bounds_unavailable(f"league rules blocked: {exc}")
    if profile.get("bounds_multi_club_prefix") is None:
        return _bounds_unavailable("the rule profile has no verified settings for position ranges")
    inp = SeasonInput(teams=teams, names=names, played_home=np.array([idx[r["h"]] for r in played], dtype=int), played_away=np.array([idx[r["a"]] for r in played], dtype=int),
                      played_hg=np.array([int(r["hg"]) for r in played], dtype=int), played_ag=np.array([int(r["ag"]) for r in played], dtype=int), fix_home=fh, fix_away=fa, pmf=None)
    b = pointbounds.position_bounds(inp, profile, pointbounds.draw_outcomes(pr, n, seed))
    if b.points.shape != points.shape or not np.array_equal(b.points, points):
        return _bounds_unavailable("internal consistency check failed: the ranges and the points simulation disagree, so no ranges are shown")
    bands, per_band = [], {}
    for bid, label in BOUNDS_BANDS:
        pos = profile.get("bands", {}).get(bid)
        if not pos:
            continue
        lo, hi = min(pos), max(pos)
        per_band[bid] = pointbounds.band_counts(b, lo, hi)
        bands.append(dict(id=bid, label=label, positions=[lo, hi], places=hi - lo + 1))
    clubs = []
    for t in np.argsort(-points.mean(axis=0), kind="stable"):                           # same order as the expected-points table
        club = dict(entity_id=teams[t], name=names[t])
        for bid, (sure, poss) in per_band.items():
            g, p = float(sure[t]) / n, float(poss[t]) / n
            club[bid] = dict(guaranteed=g, possible=p, unresolved=float(poss[t] - sure[t]) / n, se_guaranteed=float(np.sqrt(g * (1 - g) / n)), se_possible=float(np.sqrt(p * (1 - p) / n)))
        clubs.append(club)
    sums = {bd["id"]: dict(places=bd["places"], sum_guaranteed=float(per_band[bd["id"]][0].sum()) / n, sum_possible=float(per_band[bd["id"]][1].sum()) / n) for bd in bands}
    checks = dict(lower_never_above_upper=all(c[bd["id"]]["guaranteed"] <= c[bd["id"]]["possible"] for c in clubs for bd in bands),
                  all_values_between_0_and_100_percent=all(0.0 <= c[bd["id"]][k] <= 1.0 for c in clubs for bd in bands for k in ("guaranteed", "possible", "unresolved")),
                  places_sums_consistent=all(v["sum_guaranteed"] <= v["places"] + 1e-9 and v["sum_possible"] >= v["places"] - 1e-9 for v in sums.values()), places_sums=sums)
    if not (checks["lower_never_above_upper"] and checks["all_values_between_0_and_100_percent"] and checks["places_sums_consistent"]):
        return _bounds_unavailable("internal consistency check failed: a lower bound exceeded its upper bound, a value left 0-100%, or the places do not add up, so no ranges are shown")
    prefix = int(profile["bounds_multi_club_prefix"])
    return dict(status="available", label=BOUNDS_LABEL, kind="lower_and_upper_bounds", meaning=BOUNDS_MEANING, method=BOUNDS_METHOD, bands=bands, clubs=clubs, checks=checks,
                ties=dict(tie_groups=b.stats["tie_groups"], tie_groups_fully_decided=b.stats["fully_decided_tie_groups"], simulations=n),
                rules=dict(profile_id=f"{key}|{season}", status=profile["status"], sources=[{k: x.get(k) for k in ("title", "url", "sha256")} for x in profile.get("sources", [])], live_confirmation=profile.get("live_confirmation"),
                           criteria_used=dict(two_clubs=profile["criteria"]["two_clubs"], three_or_more_clubs=profile["criteria"]["multi_clubs"][:prefix]),
                           deciders_never_simulated=profile.get("terminal"), interpretation_notes=profile.get("interpretation_notes", [])),
                limitations=BOUNDS_LIMITATIONS + list(profile.get("bounds_notes", [])), monte_carlo=dict(simulations=n, seed=seed, standard_error_max=float(0.5 / np.sqrt(n))))


def run_points_only(key: str, season: str, n: Optional[int], seed: Optional[int], user_action: str, now: Optional[datetime] = None, today: Optional[date] = None, db_path=None) -> dict:
    """Experimental points-only simulation. Needs no scoreline method and no tie-break rules; saved only on the explicit user action."""
    if user_action != POINTS_ACTION:
        raise SimError("a points-only simulation runs only when the user explicitly presses Run points-only simulation")
    cfg = settings.load()
    n = int(n or cfg["default_simulations"])
    if not cfg["min_simulations"] <= n <= cfg["max_simulations"]:
        raise SimError(f"the number of simulations must be between {cfg['min_simulations']} and {cfg['max_simulations']}")
    now = now or datetime.now(timezone.utc)
    seed = int(seed) if seed is not None else secrets.randbits(31)
    conn = store_db.connect(db_path)
    try:
        st = eligibility.assess(conn, key, season, today)
        if not st["points_only"]["can_run"]:
            raise SimError("points-only simulation blocked: " + "; ".join(st["points_only"]["blockers"]))
        rows = _season_rows(conn, key, season)
        played = [r for r in rows if r["status"] in eligibility.COMPLETED and r["hg"] is not None]
        pid = {r["record_id"] for r in played}
        rem = [r for r in rows if r["record_id"] not in pid]
        probs, latest_model = live_probabilities(conn, key, season, rem)
        teams = sorted({r["h"] for r in rows} | {r["a"] for r in rows})
        idx = {t: i for i, t in enumerate(teams)}
        names = _names(conn, teams)
        base = np.zeros(len(teams), dtype=np.int64)
        for r in played:
            base[idx[r["h"]]] += 3 if r["hg"] > r["ag"] else 1 if r["hg"] == r["ag"] else 0
            base[idx[r["a"]]] += 3 if r["ag"] > r["hg"] else 1 if r["hg"] == r["ag"] else 0
        fh = np.array([idx[r["h"]] for r in rem], dtype=int)
        fa = np.array([idx[r["a"]] for r in rem], dtype=int)
        pr = probs.set_index("record_id").loc[[r["record_id"] for r in rem]][["p1_H", "p1_D", "p1_A"]].values
        points = pointsonly.simulate_points(base, fh, fa, pr, n, seed)
        remaining = np.bincount(np.concatenate([fh, fa]), minlength=len(teams)) if len(rem) else np.zeros(len(teams), dtype=int)
        summary = pointsonly.summarize_points(points, teams, [names.get(t, t) for t in teams], base, remaining, seed)
        try:
            bounds = build_position_bounds(key, season, teams, [names.get(t, t) for t in teams], idx, played, fh, fa, pr, n, seed, points)
        except Exception as exc:                                                    # the approved points results must never depend on the experimental ranges
            log.exception("position ranges failed")
            bounds = _bounds_unavailable(f"the ranges could not be computed ({type(exc).__name__}); the points results are unaffected")
        import forecast

        ids, hashes = forecast.model_ids(), forecast.artifact_hashes()
        input_hash = hashlib.sha256(json.dumps([[r["record_id"], r["status"], r["hg"], r["ag"]] for r in rows] + probs[["p1_H", "p1_D", "p1_A"]].round(10).values.tolist(), default=str).encode()).hexdigest()
        assumptions = dict(
            mode="points_only", label=POINTS_LABEL, created_utc=now.strftime("%Y-%m-%dT%H:%M:%SZ"), note=NOTE, user_action=user_action, simulations=n, seed=seed,
            models=dict(primary=ids["club_v1"]), artifact_sha256={"club_v1": hashes["club_v1"]}, probability_state="frozen club v1 features at the data cut-off, static during the simulation",
            points_rule="home win 3 points, draw 1 point each, away win 3 points; no scores are invented and no tie is settled by chance",
            position_bounds=dict(status=bounds["status"], reason=bounds.get("reason"), method=BOUNDS_METHOD if bounds["status"] == "available" else None, rule_profile=f"{key}|{season}"),
            data_cutoff=dict(latest_result_in_competition=st["latest_result"], latest_result_in_model_history=str(latest_model.date())), freshness=_freshness(conn, key, season, rows),
            eligibility=dict(state=st["state"], reasons=st["reasons"], notes=st["notes"], counts=st["counts"], thresholds=st["thresholds"]), remaining_fixtures=len(rem), input_sha256=input_hash,
            limitations=POINTS_LIMITATIONS, standard_error_max=summary["standard_error_of_a_probability_max"])
        result_json = dict(mode="points_only", summary=summary, position_bounds=bounds)
        with conn:
            run_id = conn.execute("INSERT INTO simulation_runs(created_utc, competition_key, season, n_simulations, seed, model_id, data_cutoff_date, assumptions_json, result_json) VALUES (?,?,?,?,?,?,?,?,?)",
                                  (assumptions["created_utc"], key, season, n, seed, ids["club_v1"], st["latest_result"], json.dumps(assumptions), json.dumps(result_json))).lastrowid
        return dict(run_id=run_id, competition_key=key, season=season, assumptions=assumptions, result=result_json)
    finally:
        conn.close()
